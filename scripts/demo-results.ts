  p(`- Committed build result unchanged: **${cr?.build_result_unchanged}** (gen ${cr?.build_gen}); prove attempts: ${JSON.stringify(cr?.prove_attempts)}.`);
  p(`- Final: ${cr?.final_status}; report ${short(cr?.report?.digest)} bound to payload ${short(cr?.report?.subject)}.`);
