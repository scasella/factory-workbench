  const pj = step("pinned_job");
  const c2 = step("cr2");
  const by = step("bypass_attempts");
  const bm = step("benchmark");
  const jv = step("journal_verify");
  const fin = step("final");
  p("## Founding demonstration (P0 → P1 → P2)");
  p();
