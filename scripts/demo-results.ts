  p("### 2. P0 builds P1 (parallel independent reviews)");
  p(`- Change \`${c1?.change}\`; evaluation jobs and their governing (pinned) release: ${(c1?.governed_by ?? []).map((g: any) => `\`${g.job}\`=${g.status} on ${short(g.pinned_release)}`).join(", ")}.`);
