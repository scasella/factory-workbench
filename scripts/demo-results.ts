  p(`| P0 (genesis, human-authorized trust root) | ${short(fin?.releases?.P0)} | — |`);
  p(`| P1 (authored + evaluated under P0) | ${short(fin?.releases?.P1)} | ${short(c2?.binary_P1)} |`);
  p(`| P2 (authored + evaluated under P1) | ${short(fin?.releases?.P2)} | ${short(c2?.binary_P2)} |`);
  p();
  p(`Verifier image \`${st?.isolation?.image_id ?? "?"}\`; isolation: ${st ? `network ${st.isolation.network}, root filesystem ${st.isolation.root_fs}, capabilities ${st.isolation.caps}, uid ${st.isolation.user}` : "?"}.`);
